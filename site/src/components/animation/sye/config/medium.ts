export type MediumSettingType = 'bool' | 'enum';

export interface MediumSetting {
  id: string;
  label: string;
  type: MediumSettingType;
  /** enum 的选项 */
  options?: string[];
  /** bool 是布尔，enum 是选项字符串 */
  def: string | boolean;
  /** 所属分组 id */
  group: string;
  /** 首页是否直接列出 */
  essential?: boolean;
  desc: string;
  /** 区分不同页面的导航项标签（分组页名用 MEDIUM_GROUPS 里的 name） */
  page?: string;
}

export interface MediumGroup {
  id: string;
  name: string;
}

