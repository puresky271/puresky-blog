/**
 * 把像素画转成一条 SVG path：每行连续的 '#' 合并成一个矩形子路径，
 * 比逐像素生成 rect 省掉大量节点。
 */
export function toGlyph(rows: string[]): string {
  const parts: string[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      if (row[x] !== '#') continue;
      let w = 1;
      while (row[x + w] === '#') w += 1;
      parts.push(`M${x} ${y}h${w}v1h-${w}z`);
      x += w - 1;
    }
  });
  return `<path d="${parts.join('')}"/>`;
}

/**
 * 提取像素网格中的所有实心坐标，按相对中心 (7.5, 7.5) 的极角与半径稳定排序。
 * 在不同分类图案之间切换时，像素粒子沿外圈与内圈自然对应滑移，变形轨迹更舒展。
 */
export function artCoords(rows: string[]): [number, number][] {
  const coords: [number, number][] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x += 1) {
      if (row[x] === '#') coords.push([x, y]);
    }
  });
  return coords.sort((a, b) => {
    const angleA = Math.atan2(a[1] - 7.5, a[0] - 7.5);
    const angleB = Math.atan2(b[1] - 7.5, b[0] - 7.5);
    if (Math.abs(angleA - angleB) > 0.001) return angleA - angleB;
    const distA = (a[0] - 7.5) ** 2 + (a[1] - 7.5) ** 2;
    const distB = (b[0] - 7.5) ** 2 + (b[1] - 7.5) ** 2;
    return distA - distB;
  });
}

export const CATEGORY_POINTS = Object.fromEntries(
  Object.entries(CATEGORY_ART).map(([id, rows]) => [id, artCoords(rows)])
) as Record<CategoryId, [number, number][]>;

export const MAX_CATEGORY_PIXELS = Math.max(
  ...Object.values(CATEGORY_POINTS).map((pts) => pts.length)
);
